public class OperacoesMatematicas {

    public static void main(String[] args) {
        // Declarar as variáveis para armazenar os resultados
        double som, sub, div, mul;

        // Realizar as operações matemáticas
        som = 12 + 3;
        sub = 7 - 2;
        div = 2 / 2.0; // Usando 2.0 para garantir que a divisão seja em ponto flutuante
        mul = 2 * 3;

        // Exibir os resultados
        System.out.println("A soma de 12 + 3 é igual: " + som);
        System.out.println("A subtração de 7 - 2 é: " + sub);
        System.out.println("2 / 2 é igual a: " + div);
        System.out.println("2 * 3 é igual a: " + mul);
    }
}
