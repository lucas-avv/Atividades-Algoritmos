public class ContagemEntre100e200 {

    public static void main(String[] args) {
        // Declarar variável para o contador
        int cont = 101;
        
        // Laço "enquanto" (while) para imprimir números entre 100 e 200
        while (cont < 200) {
            System.out.println("Contagem: " + cont);
            cont++;
        }
    }
}
